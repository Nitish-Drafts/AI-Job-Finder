@router.get("/cover-letters/{cl_id}/download/{file_format}")
async def download_cover_letter(
    cl_id: int,
    file_format: str,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_active_user)
) -> Any:
    """
    Compile and download cover letter as PDF or DOCX file format.
    """
    if file_format.lower() not in ["pdf", "docx"]:
        raise HTTPException(status_code=400, detail="Invalid format. Supported: pdf, docx")
        
    query = select(CoverLetter).where(
        and_(CoverLetter.id == cl_id, CoverLetter.user_id == current_user.id)
    )
    result = await db.execute(query)
    cl = result.scalar_one_or_none()
    if not cl:
        raise HTTPException(status_code=404, detail="Cover letter not found.")
        
    # Setup temporary download directories
    temp_dir = os.path.join(settings.UPLOAD_DIR, "downloads")
    os.makedirs(temp_dir, exist_ok=True)
    
    unique_name = f"cover_letter_{cl_id}_{uuid.uuid4()}"
    
    if file_format.lower() == "pdf":
        file_path = os.path.join(temp_dir, f"{unique_name}.pdf")
        optimization_service.export_pdf(cl.content, file_path)
        media_type = "application/pdf"
    else:
        file_path = os.path.join(temp_dir, f"{unique_name}.docx")
        optimization_service.export_docx(cl.content, file_path)
        media_type = "application/vnd.openxmlformats-officedocument.wordprocessingml.document"
        
    return FileResponse(
        path=file_path,
        media_type=media_type,
        filename=f"Cover_Letter_{cl_id}.{file_format.lower()}"
    )


@router.post("/interview-prep", response_model=List[InterviewQuestionOut])
async def generate_interview_prep(
    job_id: int,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_active_user)
) -> Any:
    """
    Generate tailored interview prep questions (technical, behavioral, etc.) based on a job description.
    Saves questions in user portfolio.
    """
    job_query = select(Job).where(Job.id == job_id)
    job_exec = await db.execute(job_query)
    job = job_exec.scalar_one_or_none()
    if not job:
        raise HTTPException(status_code=404, detail="Job posting not found.")
        
    # Get company name
    comp_query = select(Company).where(Company.id == job.company_id)
    comp_exec = await db.execute(comp_query)
    company = comp_exec.scalar_one_or_none()
    company_name = company.name if company else "Target Company"
    
    questions = await optimization_service.generate_interview_questions(
        job.title, company_name, job.description
    )
    
    saved_records = []
    for q in questions:
        # Avoid duplicates for same user/job/question text
        dupe_chk = await db.execute(
            select(InterviewQuestion).where(
                and_(
                    InterviewQuestion.user_id == current_user.id,
                    InterviewQuestion.job_id == job_id,
                    InterviewQuestion.question == q["question"]
                )
            )
        )
        existing = dupe_chk.scalar_one_or_none()
        if existing:
            saved_records.append(existing)
            continue
            
        record = InterviewQuestion(
            user_id=current_user.id,
            job_id=job_id,
            question_type=q["question_type"],
            question=q["question"],
            expected_answer=q["expected_answer"],
            difficulty=q["difficulty"]
        )
        db.add(record)
        saved_records.append(record)
        
    await db.commit()
    
    # Return details
    result = await db.execute(
        select(InterviewQuestion).where(
            and_(InterviewQuestion.user_id == current_user.id, InterviewQuestion.job_id == job_id)
        )
    )
    return result.scalars().all()


