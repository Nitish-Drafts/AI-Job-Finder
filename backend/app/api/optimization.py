@router.post("/resume")
async def optimize_user_resume(
    job_id: int,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_active_user)
) -> Any:
    """
    Generate an ATS-optimized summary, skills, and projects for a specific job posting compared to user's resume.
    """
    # Fetch active resume
    res_query = select(Resume).where(Resume.user_id == current_user.id).order_by(Resume.created_at.desc())
    res_exec = await db.execute(res_query)
    resume = res_exec.scalar_one_or_none()
    
    if not resume:
        raise HTTPException(
            status_code=400,
            detail="No uploaded resume found. Please upload a PDF/DOCX resume first."
        )
        
    # Fetch target job
    job_query = select(Job).where(Job.id == job_id)
    job_exec = await db.execute(job_query)
    job = job_exec.scalar_one_or_none()
    if not job:
        raise HTTPException(status_code=404, detail="Job posting not found.")
        
    optimization = await optimization_service.optimize_resume(
        resume.raw_text or "", job.title, job.description
    )
    return optimization


@router.post("/cover-letter", response_model=CoverLetterOut)
async def generate_user_cover_letter(
    job_id: int,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_active_user)
) -> Any:
    """
    Generate a personalized cover letter matching the user's resume and a specific job posting.
    Saves it to the database for subsequent edits/downloads.
    """
    res_query = select(Resume).where(Resume.user_id == current_user.id).order_by(Resume.created_at.desc())
    res_exec = await db.execute(res_query)
    resume = res_exec.scalar_one_or_none()
    
    if not resume:
        raise HTTPException(
            status_code=400,
            detail="No uploaded resume found. Please upload a PDF/DOCX resume first."
        )
        
    job_query = select(Job).where(Job.id == job_id)
    job_exec = await db.execute(job_query)
    job = job_exec.scalar_one_or_none()
    if not job:
        raise HTTPException(status_code=404, detail="Job posting not found.")
        
    # Get company name
    comp_query = select(Company).where(Company.id == job.company_id)
    comp_exec = await db.execute(comp_query)
    company = comp_exec.scalar_one_or_none()
    company_name = company.name if company else "Target Company"
    
    # Generate cover letter text
    letter_text = await optimization_service.generate_cover_letter(
        resume.raw_text or "", job.title, company_name, job.description
    )
    
    # Save or update cover letter
    cl_query = select(CoverLetter).where(
        and_(CoverLetter.user_id == current_user.id, CoverLetter.job_id == job_id)
    )
    cl_exec = await db.execute(cl_query)
    cl = cl_exec.scalar_one_or_none()
    
    if cl:
        cl.content = letter_text
    else:
        cl = CoverLetter(user_id=current_user.id, job_id=job_id, content=letter_text)
        db.add(cl)
        
    await db.commit()
    await db.refresh(cl)
    
    # Reload with full relations
    stmt = select(CoverLetter).options(selectinload(CoverLetter.job).selectinload(Job.company)).where(CoverLetter.id == cl.id)
    res = await db.execute(stmt)
    return res.scalar_one()


